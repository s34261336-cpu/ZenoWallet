create or replace function public.season_ensure_active()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_season public.seasons%rowtype;
begin
  select *
    into v_season
    from public.seasons
   where status = 'active'
   order by starts_at desc
   limit 1;

  if not found then
    insert into public.seasons (season_number, starts_at, ends_at)
    values (
      coalesce((select max(season_number) from public.seasons), 0) + 1,
      now(),
      now() + interval '3 days'
    )
    returning * into v_season;
  end if;

  return jsonb_build_object(
    'season_id', v_season.id,
    'starts_at', v_season.starts_at,
    'ends_at', v_season.ends_at,
    'status', v_season.status
  );
end;
$$;

create or replace function public.crash_multiplier_for(p_started_at timestamptz)
returns numeric
language plpgsql
volatile
set search_path = public
as $$
declare
  v_elapsed numeric;
begin
  v_elapsed := greatest(
    0,
    extract(epoch from (clock_timestamp() - p_started_at))
  );
  -- Matches the client animation: about 1.08x, 1.26x, 1.47x...
  -- at one-second intervals after the 3–2–1 pre-launch countdown.
  return round((1 + (0.07 * v_elapsed) + (0.025 * v_elapsed * v_elapsed))::numeric, 2);
end;
$$;

create or replace function public.crash_start(
  p_user_id bigint,
  p_bet bigint,
  p_crash_at numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_wallet public.wallet%rowtype;
  v_game public.games%rowtype;
begin
  if p_bet is null or p_bet <= 0 then
    raise exception 'Ставка должна быть больше нуля';
  end if;
  if p_crash_at is null or p_crash_at < 1.2 or p_crash_at > 500 then
    raise exception 'Некорректная точка краша';
  end if;

  insert into public.wallet (user_id, earn_balance, zeno_balance)
  values (p_user_id, 0, 0)
  on conflict (user_id) do nothing;

  select *
    into v_wallet
    from public.wallet
   where user_id = p_user_id
   for update;

  if v_wallet.earn_balance < p_bet then
    raise exception 'Недостаточно монет для этой ставки';
  end if;

  update public.wallet
     set earn_balance = earn_balance - p_bet,
         updated_at = now()
   where user_id = p_user_id;

  insert into public.games (
    user_id, game_name, bet, result, crash_at
  )
  values (
    p_user_id, 'rocket', p_bet, 'active', round(p_crash_at, 2)
  )
  returning * into v_game;

  return jsonb_build_object(
    'gameId', v_game.id,
    'bet', v_game.bet,
    'startedAt', v_game.started_at,
    'crashAt', v_game.crash_at,
    'balance', v_wallet.earn_balance - p_bet
  );
end;
$$;

create or replace function public.crash_cashout(
  p_user_id bigint,
  p_game_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game public.games%rowtype;
  v_wallet public.wallet%rowtype;
  v_live_multiplier numeric;
  v_payout bigint;
begin
  select *
    into v_game
    from public.games
   where id = p_game_id
     and user_id = p_user_id
     and game_name = 'rocket'
   for update;

  if not found then
    raise exception 'Раунд не найден';
  end if;
  if v_game.result <> 'active' then
    select *
      into v_wallet
      from public.wallet
     where user_id = p_user_id;
    return jsonb_build_object(
      'gameId', v_game.id,
      'result', v_game.result,
      'bet', v_game.bet,
      'multiplier', coalesce(v_game.multiplier, v_game.crash_at),
      'payout', v_game.payout,
      'balance', v_wallet.earn_balance
    );
  end if;

  v_live_multiplier := public.crash_multiplier_for(v_game.started_at);
  if v_live_multiplier >= v_game.crash_at then
    update public.games
       set result = 'lost',
           multiplier = v_game.crash_at,
           payout = 0,
           settled_at = now()
     where id = v_game.id;

    select *
      into v_wallet
      from public.wallet
     where user_id = p_user_id;

    return jsonb_build_object(
      'gameId', v_game.id,
      'result', 'lost',
      'bet', v_game.bet,
      'multiplier', v_game.crash_at,
      'payout', 0,
      'balance', v_wallet.earn_balance
    );
  end if;

  v_live_multiplier := least(v_live_multiplier, v_game.crash_at);
  v_payout := floor(v_game.bet * v_live_multiplier)::bigint;

  select *
    into v_wallet
    from public.wallet
   where user_id = p_user_id
   for update;

  update public.wallet
     set earn_balance = earn_balance + v_payout,
         updated_at = now()
   where user_id = p_user_id;

  update public.games
     set result = 'won',
         multiplier = v_live_multiplier,
         payout = v_payout,
         settled_at = now()
   where id = v_game.id;

  return jsonb_build_object(
    'gameId', v_game.id,
    'result', 'won',
    'bet', v_game.bet,
    'multiplier', v_live_multiplier,
    'payout', v_payout,
    'balance', v_wallet.earn_balance + v_payout
  );
end;
$$;

