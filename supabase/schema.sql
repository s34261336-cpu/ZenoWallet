-- Seasonal competitions. These tables are intentionally separate from
-- bot_state so season data can be reset without touching bot settings/users.
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  season_number bigint not null default 1,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'active'
    check (status in ('active', 'finished')),
  finished_at timestamptz,
  announcement_sent_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.seasons
  add column if not exists season_number bigint;

update public.seasons
   set season_number = id
 where season_number is null;

alter table public.seasons
  alter column season_number set default 1,
  alter column season_number set not null;

create unique index if not exists seasons_one_active_idx
  on public.seasons (status)
  where status = 'active';

create table if not exists public.season_scores (
  season_id bigint not null references public.seasons(id) on delete cascade,
  user_id bigint not null,
  username text,
  display_name text not null default '',
  points bigint not null default 0 check (points >= 0),
  activity_count bigint not null default 0 check (activity_count >= 0),
  cases_opened bigint not null default 0 check (cases_opened >= 0),
