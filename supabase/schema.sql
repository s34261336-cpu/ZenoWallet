-- Zeno Wallet storage.
-- Run this once in the Supabase SQL editor for the project used by Zeno.

create table if not exists public.wallet (
  user_id bigint primary key,
  earn_balance bigint not null default 0 check (earn_balance >= 0),
  zeno_balance bigint not null default 0 check (zeno_balance >= 0),
  updated_at timestamptz not null default now(),
  daily_claimed_at timestamptz,
  referred_by bigint,
  referral_rewarded boolean not null default false
);

alter table public.wallet
  add column if not exists daily_claimed_at timestamptz,
  add column if not exists referred_by bigint,
  add column if not exists referral_rewarded boolean not null default false;

create index if not exists wallet_updated_at_idx
  on public.wallet (updated_at desc);

-- Rocket crash game. Active rounds are kept in the database so a restart
-- cannot silently erase a user's in-flight bet.
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  game_name text not null,
  bet bigint not null check (bet > 0),
  multiplier numeric(10, 2),
  result text not null default 'active'
    check (result in ('active', 'won', 'lost')),
  created_at timestamptz not null default now(),
  started_at timestamptz not null default now(),
  crash_at numeric(10, 2) not null check (crash_at >= 1.2 and crash_at <= 500),
  payout bigint not null default 0 check (payout >= 0),
  settled_at timestamptz
);

alter table public.games
  add column if not exists started_at timestamptz not null default now(),
  add column if not exists crash_at numeric(10, 2),
  add column if not exists payout bigint not null default 0,
  add column if not exists settled_at timestamptz;

-- Roulette rows share this ledger but do not have a crash point.
alter table public.games
  alter column crash_at drop not null;

-- Upgrade the first crash-game migration from the old 1.5x–10x range.
alter table public.games drop constraint if exists games_crash_at_check;
alter table public.games drop constraint if exists games_crash_at_range_check;
do $$
begin
  if not exists (
    select 1
      from pg_constraint
     where conrelid = 'public.games'::regclass
       and conname = 'games_crash_at_range_check'
  ) then
    alter table public.games
      add constraint games_crash_at_range_check
      check (crash_at >= 1.2 and crash_at <= 500);
  end if;
end;
$$;

create index if not exists games_user_history_idx
  on public.games (user_id, game_name, created_at desc);

create unique index if not exists games_one_active_rocket_idx
  on public.games (user_id, game_name)
  where result = 'active' and game_name = 'rocket';

-- Roulette uses the same immutable game ledger as crash, with one daily
-- counter per user and one global jackpot lock per UTC day.
create table if not exists public.roulette_daily (
  user_id bigint not null,
  play_date date not null default current_date,
  free_plays_used integer not null default 0 check (free_plays_used >= 0),
  primary key (user_id, play_date)
);

create table if not exists public.roulette_jackpot_daily (
  play_date date primary key default current_date,
  claimed_at timestamptz,
  claimed_by bigint
);

